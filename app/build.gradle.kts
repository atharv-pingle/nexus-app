// Dynamic Versioning from version.properties and CI GITHUB_RUN_NUMBER
val versionPropsFile = rootProject.file("version.properties")
val versionProps = Properties()
if (versionPropsFile.exists()) {
    versionProps.load(FileInputStream(versionPropsFile))
}

val major = versionProps.getProperty("major", "1").toInt()
val minor = versionProps.getProperty("minor", "0").toInt()
val patch = versionProps.getProperty("patch", "0").toInt()
val localBuild = versionProps.getProperty("build", "1").toInt()

val ciRunNumber = System.getenv("GITHUB_RUN_NUMBER")?.toIntOrNull()
val computedVersionCode = ciRunNumber ?: localBuild
val computedVersionName = if (ciRunNumber != null) {
    "$major.$minor.$patch.$ciRunNumber"
} else {
    "$major.$minor.$patch-dev$localBuild"
}

